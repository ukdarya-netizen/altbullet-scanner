const SET = new Set<number>(LC_FILTER_EXCLUDED_SIGNAL_IDS);

export function isLcFilterExcludedSignal(
  id: number | null | undefined,
): boolean {
  return id != null && SET.has(Number(id));
}

import { sql, type SQL } from "drizzle-orm";

/** SQL predicate that is true for rows kept in statistics. */
export function lcStatsExclusionSql(idColumn: SQL, keyColumn: SQL): SQL {
  const ids = sql.join(
    LC_FILTER_EXCLUDED_SIGNAL_IDS.map((id) => sql`${id}`),
    sql`, `,
  );
  return sql`NOT (${keyColumn} = 'liquidation_cascade' AND ${idColumn} IN (${ids}))`;
}
